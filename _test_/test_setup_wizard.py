# ServerProcess — unit tests (no real subprocess)
# ══════════════════════════════════════════════════════════════════════════

def make_server() -> sl.ServerProcess:
    return sl.ServerProcess(on_log=lambda m: None, on_status_change=lambda s: None)


def test_server_initial_status_is_stopped():
    s = make_server()
    assert s.status == "stopped"
    assert not s.is_running()


def test_server_start_sets_running(tmp_path):
    import threading as _threading
    statuses = []
    reached_running = _threading.Event()

    def on_status(s):
        statuses.append(s)
        if s == "running":
            reached_running.set()

    s = sl.ServerProcess(on_log=lambda m: None, on_status_change=on_status)
    mock_proc = MagicMock()
    mock_proc.poll.return_value = None
    mock_proc.stdout = iter([])
    wait_released = _threading.Event()
    mock_proc.wait.side_effect = lambda: wait_released.wait()
    mock_proc.returncode = 0

    with patch("subprocess.Popen", return_value=mock_proc):
        s.start()

    reached_running.wait(timeout=2)
    assert "running" in statuses
    wait_released.set()


def test_server_stop_sets_stopped(tmp_path):
    s = make_server()
    mock_proc = MagicMock()
    mock_proc.poll.return_value = None
    mock_proc.stdout = iter([])
    mock_proc.returncode = 0

    with patch("subprocess.Popen", return_value=mock_proc):
        s.start()

    mock_proc.poll.return_value = 0   # process has exited after terminate()
    s.stop()
    assert s.status == "stopped"
    assert not s.is_running()


def test_server_start_twice_does_not_spawn_second_process():
    s = make_server()
    mock_proc = MagicMock()
    mock_proc.poll.return_value = None
    mock_proc.stdout = iter([])

    with patch("subprocess.Popen", return_value=mock_proc) as popen_mock:
        s.start()
        s.start()   # second call — should be no-op
    assert popen_mock.call_count == 1


def test_server_stop_when_not_running_is_safe():
    s = make_server()
    s.stop()   # should not raise
    assert s.status == "stopped"


def test_server_logs_startup_command():
    logs = []
    s = sl.ServerProcess(on_log=logs.append, on_status_change=lambda _: None)
    mock_proc = MagicMock()
    mock_proc.poll.return_value = None
    mock_proc.stdout = iter([])

    with patch("subprocess.Popen", return_value=mock_proc):
        s.start()

    assert any("obsidian-mcp" in l for l in logs)


