def test_create_shortcut_windows_calls_powershell():
    with patch("platform.system", return_value="Windows"), \
         patch("subprocess.check_call") as mock_call, \
         patch("pathlib.Path.home", return_value=Path("/fake/home")):
        # Patch Desktop to a tmp dir to avoid actually writing
        fake_desktop = Path("/fake/home/Desktop")
        with patch.object(Path, "mkdir", return_value=None), \
             patch("builtins.open", mock.mock_open()):
            sw.create_desktop_shortcut()
