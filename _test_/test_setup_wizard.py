# ══════════════════════════════════════════════════════════════════════════

def test_merge_creates_new_config(tmp_path):
    cfg_path = tmp_path / "claude_desktop_config.json"
    with patch("setup_wizard.get_claude_desktop_config_path", return_value=cfg_path):
        ok, msg = sw.merge_claude_desktop_config(
            ["uv", "run", "obsidian-mcp"],
            {"OBSIDIAN_MCP_VAULT_PATH": "/vault"},
        )
    assert ok
    data = json.loads(cfg_path.read_text())
    assert "obsidian-mcp" in data["mcpServers"]
    assert data["mcpServers"]["obsidian-mcp"]["command"] == "uv"
    assert data["mcpServers"]["obsidian-mcp"]["args"] == ["run", "obsidian-mcp"]


def test_merge_preserves_existing_servers(tmp_path):
    cfg_path = tmp_path / "claude_desktop_config.json"
    existing = {
        "mcpServers": {
            "another-mcp": {"command": "python", "args": ["-m", "other"]}
        }
    }
    cfg_path.write_text(json.dumps(existing))
    with patch("setup_wizard.get_claude_desktop_config_path", return_value=cfg_path):
        ok, _ = sw.merge_claude_desktop_config(["uv", "run", "obsidian-mcp"], {})
    assert ok
    data = json.loads(cfg_path.read_text())
    assert "another-mcp" in data["mcpServers"], "Existing server was overwritten!"
    assert "obsidian-mcp" in data["mcpServers"]


def test_merge_overwrites_existing_obsidian_mcp_entry(tmp_path):
    cfg_path = tmp_path / "claude_desktop_config.json"
    existing = {
        "mcpServers": {
            "obsidian-mcp": {"command": "old_cmd", "args": []}
        }
    }
    cfg_path.write_text(json.dumps(existing))
    with patch("setup_wizard.get_claude_desktop_config_path", return_value=cfg_path):
        ok, _ = sw.merge_claude_desktop_config(["uv", "run", "obsidian-mcp"], {})
    assert ok
    data = json.loads(cfg_path.read_text())
    assert data["mcpServers"]["obsidian-mcp"]["command"] == "uv"


def test_merge_fails_on_invalid_json(tmp_path):
    cfg_path = tmp_path / "claude_desktop_config.json"
    cfg_path.write_text("NOT VALID JSON {{{")
    with patch("setup_wizard.get_claude_desktop_config_path", return_value=cfg_path):
        ok, msg = sw.merge_claude_desktop_config(["uv", "run", "obsidian-mcp"], {})
    assert not ok
    assert "not valid JSON" in msg


def test_merge_atomic_write(tmp_path):
    """Verify .tmp is cleaned up and final file is valid."""
    cfg_path = tmp_path / "claude_desktop_config.json"
    tmp_file = cfg_path.with_suffix(".tmp")
    with patch("setup_wizard.get_claude_desktop_config_path", return_value=cfg_path):
        sw.merge_claude_desktop_config(["uv", "run", "obsidian-mcp"], {})
    assert not tmp_file.exists(), ".tmp file was not cleaned up"
    assert cfg_path.exists()


